"""Partial-write failure tests: a failure at each persistence stage returns a safe 503, never a
successful 'persisted' result, leaves the ticket diagnosable, and retries do not duplicate data."""
import logging

import pytest
from fastapi.testclient import TestClient
from pymongo.errors import ServerSelectionTimeoutError

from app.data_loader import load_json
from app.db import PersistenceError, get_database
from app.main import app
from app.repositories import get_ticket
from app.services import ticket_service

S = load_json("sample_requests.json")
FAKE_URI = "mongodb://appuser:S3cretPass@db.example.internal:27017/"


@pytest.fixture
def client():
    with TestClient(app) as c:
        yield c


@pytest.fixture
def created(monkeypatch):
    """Record the ticket id generated by the service."""
    seen = {}
    real_create = ticket_service.create_ticket

    def spy(document, **kw):
        seen["id"] = document["ticket_id"]
        return real_create(document, **kw)

    monkeypatch.setattr(ticket_service, "create_ticket", spy)
    return seen


def _boom_pymongo(*_a, **_k):
    # Message mimics a driver error that embeds connection details; it must never reach clients/logs.
    raise ServerSelectionTimeoutError(f"No servers found for {FAKE_URI}")


def _post(client, key="happy_path", **extra):
    return client.post("/api/workflow", json={"text": S[key], "today": "2026-10-17", **extra})


def _assert_safe_503(r):
    assert r.status_code == 503
    assert "persisted" not in r.json()
    for secret in ("mongodb://", "S3cretPass", "appuser", "db.example.internal", "Traceback"):
        assert secret not in r.text


def test_failure_creating_ticket(client, monkeypatch):
    monkeypatch.setattr("app.repositories.ticket_repository._resolve_db",
                        lambda db: type("D", (), {"tickets": type("C", (), {"insert_one": _boom_pymongo})()})())
    _assert_safe_503(_post(client))
    assert get_database().tickets.count_documents({}) == 0


@pytest.mark.parametrize("stage", ["upsert_draft_po", "append_audit_entries", "update_ticket_result"])
def test_failure_at_each_later_stage(client, monkeypatch, created, stage):
    def boom(*_a, **_k):
        raise PersistenceError()

    monkeypatch.setattr(ticket_service, stage, boom)
    _assert_safe_503(_post(client))

    doc = get_ticket(created["id"])
    assert doc["status"] == "persistence_error"
    assert doc["workflow_result"] is None  # snapshot never claims success
    assert "Persistence error" in doc["error"]


def test_failure_after_po_write_is_diagnosable(client, monkeypatch, created):
    """Audit write fails after the PO was saved: partial state exists but the ticket says so."""
    monkeypatch.setattr(ticket_service, "append_audit_entries",
                        lambda *a, **k: (_ for _ in ()).throw(PersistenceError()))
    _assert_safe_503(_post(client))
    tid = created["id"]
    assert get_ticket(tid)["status"] == "persistence_error"
    assert get_database().purchase_orders.count_documents({"ticket_id": tid}) == 1
    assert get_database().agent_logs.count_documents({"ticket_id": tid}) == 0


def test_non_persistence_exception_is_wrapped(client, monkeypatch, created):
    monkeypatch.setattr(ticket_service, "upsert_draft_po",
                        lambda *a, **k: (_ for _ in ()).throw(RuntimeError(f"driver blew up {FAKE_URI}")))
    r = _post(client)
    _assert_safe_503(r)
    assert get_ticket(created["id"])["status"] == "persistence_error"


def test_success_snapshot_matches_response(client):
    res = _post(client, invoice_id="INV-5001").json()
    assert res["persisted"] is True
    stored = client.get(f"/api/tickets/{res['ticket_id']}").json()["workflow_result"]
    assert stored["persisted"] is True
    assert stored == res


def test_retry_does_not_duplicate(client, monkeypatch, created):
    """A retry of the persistence step after a failure must not duplicate the PO or audit sequence."""
    calls = {"n": 0}
    real_update = ticket_service.update_ticket_result

    def flaky(*a, **k):
        calls["n"] += 1
        if calls["n"] == 1:
            raise PersistenceError()
        return real_update(*a, **k)

    monkeypatch.setattr(ticket_service, "update_ticket_result", flaky)
    captured = {}
    real_run = ticket_service.run_workflow
    monkeypatch.setattr(ticket_service, "run_workflow",
                        lambda *a, **k: captured.setdefault("r", real_run(*a, **k)))
    assert _post(client).status_code == 503

    tid, result = created["id"], captured["r"]
    ticket_service.persist_result(tid, result)  # retry the same writes
    db = get_database()
    assert db.tickets.count_documents({"ticket_id": tid}) == 1
    assert db.purchase_orders.count_documents({"ticket_id": tid}) == 1
    assert db.agent_logs.count_documents({"ticket_id": tid}) == len(result.audit_trail)
    doc = get_ticket(tid)
    assert doc["status"] == result.final_status
    assert doc["workflow_result"]["persisted"] is True


def test_logs_do_not_leak_credentials(client, monkeypatch, caplog, created):
    monkeypatch.setattr("app.repositories.purchase_order_repository._resolve_db",
                        lambda db: type("D", (), {"purchase_orders": type("C", (), {"update_one": _boom_pymongo})()})())
    with caplog.at_level(logging.DEBUG):
        _assert_safe_503(_post(client))
    for secret in ("S3cretPass", "appuser", "db.example.internal", "mongodb://"):
        assert secret not in caplog.text
    assert S["happy_path"] not in caplog.text  # request text is not logged
